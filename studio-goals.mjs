export function inferGoal(text) {
 if(/博士.*(毕业|论文|开题)|博士毕业设计|dissertation/i.test(text)) return 'thesis';
 if(/(申请|申博|攻读|考博).*(博士|phd)|博士申请|申博|考博|apply.*phd/i.test(text)) return 'phd';
 if(/保研|推免|夏令营|研究生申请/.test(text)) return 'admission';
 if(/基金|国自然|国社科|申报/.test(text)) return 'fund';
 if(/润色|写作|投稿|英文|论文修改/.test(text)) return 'writing';
 if(/学习|学会|想学|方法|模拟|simulation|markov|DID|RDD|回归|差分|机器学习|复现|时间序列/i.test(text)) return 'method';
 return 'custom';
}

export function buildGoal(input, records=[]) {
 const id=input.type && GOALS[input.type]?input.type:inferGoal(input.target);
 const route=GOALS[id];
 const weeks=Number(input.weeks);
 const duration=Number.isFinite(weeks)&&weeks>=1&&weeks<=260?Math.floor(weeks):null;
 const phases=route.phases.map(([title,task,deliverable,check],i)=>({title,task,deliverable,check,
  schedule:duration?`第 ${Math.floor(i*duration/route.phases.length)+1}–${Math.max(Math.floor(i*duration/route.phases.length)+1,Math.floor((i+1)*duration/route.phases.length))} 周`:`阶段 ${i+1}`}));
 return {id,...route,input,duration,phases,evidence:search(records,input.target,{limit:4}),
  timing:duration?`按你填写的 ${duration} 周分配准备任务；阶段可重叠。这是工作安排草案，不是完成学位、录取或发表的保证。`:'未填写周期：先按顺序推进，拿到要求和数据条件后再安排时间。'};
}

